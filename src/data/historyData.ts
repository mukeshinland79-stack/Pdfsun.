/**
 * Returns localized string with English fallback and variable interpolation support (e.g. {{day}})
 */
export function getHistoryText(key: string, langCode: string, params?: Record<string, any>): string {
  const normalizedLang = (langCode || "en").toLowerCase().split("-")[0];
  const dict = HISTORY_I18N_DICTIONARY[normalizedLang] || HISTORY_I18N_DICTIONARY[langCode?.toLowerCase()] || HISTORY_I18N_DICTIONARY["en"];
  let text = dict && dict[key] ? dict[key] : (HISTORY_I18N_DICTIONARY["en"]?.[key] || key);

  if (params && typeof text === "string") {
    for (const [pk, pv] of Object.entries(params)) {
      text = text.replace(new RegExp(`{{${pk}}}`, "g"), String(pv));
    }
  }

  return text;
}
